    private static readonly int[] Firsts = Array.ConvertAll(Escaped, r => r.First);

    private static bool IsEscaped(int scalar)
    {
        int at = Array.BinarySearch(Firsts, scalar);
        if (at < 0) at = ~at - 1;
        return at >= 0 && scalar <= Escaped[at].Last;
    }

    /// <summary><c>format!("{:?}", text)</c>, quotes included. A lone surrogate (a .NET string may hold one; a JSON string cannot) is written as the replacement
    /// character a UTF-8 conversion gives it.</summary>
    public static string Quote(string text)
    {
        var sb = new StringBuilder(text.Length + 2).Append('"');
        foreach (var rune in text.EnumerateRunes())
        {
            switch (rune.Value)
            {
                case 0: sb.Append("\\0"); break;
                case '\t': sb.Append("\\t"); break;
                case '\r': sb.Append("\\r"); break;
                case '\n': sb.Append("\\n"); break;
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                default:
                    if (IsEscaped(rune.Value)) sb.Append("\\u{").Append(rune.Value.ToString("x", CultureInfo.InvariantCulture)).Append('}');
                    else sb.Append(rune.ToString());
                    break;
            }
        }
        return sb.Append('"').ToString();
    }
